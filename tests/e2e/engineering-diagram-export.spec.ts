import { randomBytes } from "node:crypto";
import { readFile } from "node:fs/promises";
import { expect, test } from "@playwright/test";
import { signUpThroughUi } from "./auth-helpers";

test.describe.configure({ timeout: 180_000 });

test("an engineer downloads all five control-system diagram types for the selected project", async ({
  page,
}) => {
  const id = randomBytes(8).toString("hex");
  const org = `Diagram QA ${id}`;
  const project = `Export QA ${id}`;

  await page.goto("/auth");
  await signUpThroughUi(page, `diagrams-${id}@example.com`, "Kide-Diagrams-Export!Aa1");
  await expect(page).toHaveURL("/projects");
  await page.getByPlaceholder("Acme Robotics").fill(org);
  await page.getByRole("button", { name: "Create", exact: true }).click();
  await expect(page.getByRole("heading", { name: org })).toBeVisible();

  await page.getByPlaceholder("New project name").fill(project);
  await page.getByRole("button", { name: "Project", exact: true }).click();
  await expect(page.getByRole("listitem").filter({ hasText: project })).toBeVisible();
  await expect
    .poll(() => page.evaluate(() => window.localStorage.getItem("kide:active-project")))
    .not.toBeNull();

  await page
    .getByRole("listitem")
    .filter({ hasText: project })
    .getByRole("link", { name: "Open models" })
    .click();
  await expect(page.getByText("This project has no model files yet")).toBeVisible();
  await expect(page.getByRole("button", { name: "Download diagrams" })).toBeDisabled();

  await page
    .getByRole("combobox", { name: "Reference example workspace" })
    .selectOption("precision-irrigation");
  await page.getByRole("button", { name: "Load selected" }).click();
  await expect(page.getByRole("button", { name: /^Agri\.dml/ })).toBeVisible();
  await expect(page.getByText("Saved", { exact: true })).toBeVisible();

  const downloadPromise = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download diagrams" }).click();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toMatch(/^kide-engineering-diagrams-[a-z0-9-]+\.zip$/);
  const bytes = await readFile((await download.path())!);
  expect(bytes.readUInt32LE(0)).toBe(0x04034b50);
  // ZIP store archives include six self-contained SVGs, the original model set,
  // and a manifest. These names are generated by KIDE, never from unsafe paths.
  const readable = bytes.toString("utf8");
  expect(readable).toContain("diagrams/00-system-architecture.svg");
  for (const extension of ["dml", "op", "mncspec", "cap", "activity"]) {
    expect(readable).toContain(`-${extension}.svg`);
  }
  expect(readable).toContain("modelset.json");
  expect(readable).toContain("manifest.json");
  expect(readable).toContain("snapshot-not-release-approved");
});
